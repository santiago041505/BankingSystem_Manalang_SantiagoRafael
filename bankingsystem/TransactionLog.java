private void filterTable() {
   
    Object accObj = jComboBox1.getSelectedItem();
    
    
    String selectedAccId = (accObj != null) ? accObj.toString().trim() : "";
    
    
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
    model.setRowCount(0); 
    
    TransactionDAO txDAO = new TransactionDAO();
    java.util.List<Object[]> transactions = txDAO.getAllTransactionLogs();
    
    System.out.println("Total rows pulled from database: " + (transactions != null ? transactions.size() : 0));
    
    if (transactions != null) {
        for (Object[] row : transactions) {
            String rowAccId = String.valueOf(row[1]).trim(); 
            
            
            boolean matchAcc = selectedAccId.isEmpty() || selectedAccId.startsWith("Item") || selectedAccId.equalsIgnoreCase("All") || selectedAccId.equals(rowAccId);
            
            if (matchAcc ) {
                model.addRow(row);
            }
        }}}
    
