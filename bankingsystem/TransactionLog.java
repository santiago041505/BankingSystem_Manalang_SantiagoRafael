    private void jTextField1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jTextField1ActionPerformed
String keyword = jTextField1.getText().trim();
    String searchType = jComboBox1.getSelectedItem().toString();

        if (keyword.isEmpty()) {
        refreshTable();
        return;
    }

    TransactionDAO dao = new TransactionDAO();
    java.util.List<Object[]> results = dao.searchTransactions(searchType, keyword);

    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);
    
    for (Object[] row : results) {
        model.addRow(row);
    }

    if (results.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "No transactions found for: " + keyword);
    }

    }//GEN-LAST:event_jTextField1ActionPerformed


