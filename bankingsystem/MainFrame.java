    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
 try {
       
        String searchType = jComboBox2.getSelectedItem().toString();
        String keyword = jTextField8.getText().trim();                

        if (keyword.isEmpty()) {
            refreshCustomerTable();
            return;
        }

        
        CustomerDAO dao = new CustomerDAO();
        java.util.List<Customer> results = dao.searchCustomers(searchType, keyword);

        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        model.setColumnIdentifiers(new Object[]{"Customer ID", "First Name", "Last Name", "Email", "Phone"});

        for (Customer c : results) {
            model.addRow(new Object[]{
                c.getCustomerID(),
                c.getFirstName(),
                c.getLastName(),
                c.getEmail(),
                c.getPhoneNumber()
            });
        }

        if (results.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "No records found for: " + keyword);
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Search Error: " + e.getMessage());
    }
    }//GEN-LAST:event_jButton4ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
int selectedRow = jTable1.getSelectedRow();
    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please click a row in the table first to delete.");
        return;
    }

    int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to permanently delete this record?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
    if (confirm != javax.swing.JOptionPane.YES_OPTION) return;

    try {
        int columnCount = jTable1.getColumnCount();
        int targetId = Integer.parseInt(jTable1.getValueAt(selectedRow, 0).toString());

        if (columnCount == 5) {
            new CustomerDAO().deleteCustomer(targetId);
            javax.swing.JOptionPane.showMessageDialog(this, "Customer removed.");
            refreshCustomerTable();
        } else if (columnCount == 4) {
            new AccountDAO().deleteAccount(targetId);
            javax.swing.JOptionPane.showMessageDialog(this, "Account closed/removed.");
            refreshAccountTable();
        }

        jButton7ActionPerformed(null);

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Deletion Error: " + e.getMessage());
    }      
    }//GEN-LAST:event_jButton3ActionPerformed

