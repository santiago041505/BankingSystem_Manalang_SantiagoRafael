    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        int selectedRow = jTable1.getSelectedRow();
    if (selectedRow == -1) return;

    int columnCount = jTable1.getColumnCount();

    if (columnCount == 5) {
       txtFirstName.setText(jTable1.getValueAt(selectedRow, 1).toString()); 
       txtLastName.setText(jTable1.getValueAt(selectedRow, 2).toString()); 
        txtEmail.setText(jTable1.getValueAt(selectedRow, 3).toString()); 
        txtPhone.setText(jTable1.getValueAt(selectedRow, 4).toString());
    } 
    else if (columnCount == 4) {
        jTextField3.setText(jTable1.getValueAt(selectedRow, 1).toString()); 
        
        String type = jTable1.getValueAt(selectedRow, 2).toString();        
        jComboBox1.setSelectedItem(type);
        
      txtInitialBalance.setText(jTable1.getValueAt(selectedRow, 3).toString()); 
    }
    }//GEN-LAST:event_jTable1MouseClicked

