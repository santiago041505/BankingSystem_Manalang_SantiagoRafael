    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
boolean customerAdded = false;
    boolean accountAdded = false;

    try {
       
        String firstName = txtFirstName.getText().trim();
        String lastName = txtLastName.getText().trim();
        String email = txtEmail.getText().trim();
        String phone = txtPhone.getText().trim();

       
        if (!firstName.isEmpty() && !lastName.isEmpty() && !email.isEmpty()) {
            Customer customer = new Customer(0, firstName, lastName, email, phone);
            CustomerDAO customerDAO = new CustomerDAO();
            customerDAO.addCustomer(customer);
            customerAdded = true;
            
            txtFirstName.setText("");
            txtLastName.setText("");
            txtEmail.setText("");
            txtPhone.setText("");
        }

       
        String custIdStr = jTextField3.getText().trim();
        
        String accType = "";
        if (jComboBox1.getSelectedItem() != null) {
            accType = jComboBox1.getSelectedItem().toString().trim();
        }
        
        String balanceStr = txtInitialBalance.getText().trim();

        if (!custIdStr.isEmpty() && !accType.isEmpty() && !balanceStr.isEmpty()) {
            int customerId = Integer.parseInt(custIdStr);
            double balance = Double.parseDouble(balanceStr);

            CustomerDAO custDAO = new CustomerDAO();
            if (custDAO.getCustomer(customerId) == null) {
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "Customer ID " + customerId + " not found!\nPlease verify the ID or add the customer first.", 
                    "Foreign Key Missing", 
                    javax.swing.JOptionPane.ERROR_MESSAGE);
                return; 
            }

            Account account = new Account(0, customerId, accType, balance);
            AccountDAO accountDAO = new AccountDAO();
            accountDAO.addAccount(account);
            accountAdded = true;
           
            jTextField3.setText("");
            jComboBox1.setSelectedIndex(0); 
            txtInitialBalance.setText("");
        }

        
        if (customerAdded && accountAdded) {
            javax.swing.JOptionPane.showMessageDialog(this, "Customer and Account created successfully!");
            refreshCustomerTable(); 
        } else if (customerAdded) {
            javax.swing.JOptionPane.showMessageDialog(this, "Customer saved successfully!");
            refreshCustomerTable();
        } else if (accountAdded) {
            javax.swing.JOptionPane.showMessageDialog(this, "Account linked and saved successfully!");
            refreshAccountTable();  
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Please fill in either Customer or Account fields before clicking Add.");
        }

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter valid numbers for Customer ID and Balance!", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Execution Error: " + e.getMessage());
        e.printStackTrace();
    }
    }//GEN-LAST:event_jButton1ActionPerformed
private void refreshCustomerTable() {
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
    model.setRowCount(0); 
    
   
    model.setColumnIdentifiers(new Object[]{"Customer ID", "First Name", "Last Name", "Email", "Phone"});
    
    
    CustomerDAO dao = new CustomerDAO();
    java.util.List<Customer> list = dao.getAllCustomers();
    for (Customer c : list) {
        model.addRow(new Object[]{
            c.getCustomerID(),
            c.getFirstName(), 
            c.getLastName(),  
            c.getEmail(),     
            c.getPhoneNumber()
        });
    }
}

private void refreshAccountTable() {
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
    model.setRowCount(0); // Wipe old rows clear
    
  
    model.setColumnIdentifiers(new Object[]{"Account ID", "Customer ID", "Account Type", "Balance"});
    

    AccountDAO dao = new AccountDAO();
    java.util.List<Account> list = dao.getAllAccounts();
    for (Account a : list) {
        model.addRow(new Object[]{
            a.getAccountID(),
            a.getCustomerID(),
            a.getAccountType(),
            a.getBalance()
        });
    }
}
